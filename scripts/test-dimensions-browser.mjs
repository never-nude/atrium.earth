import assert from 'node:assert/strict';
import { chromium } from 'playwright';
const base = process.env.ATRIUM_TEST_URL || 'http://127.0.0.1:4332';
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--enable-unsafe-swiftshader'] });
try {
  const page = await browser.newPage({ viewport: { width: 1365, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(`${base}/preview/dimensions/audit/`);
  assert.equal(await page.locator('[data-audit-row]').count(), 453);
  await page.locator('[data-audit-status]').selectOption('calibrated');
  assert.equal(await page.locator('[data-audit-row]:visible').count(), 9);
  await page.locator('[data-audit-row]:visible img').evaluateAll(images => Promise.all(images.slice(0, 2).map(image => image.decode())));
  await page.screenshot({ path: '/private/tmp/atrium-dimensions-audit.png' });
  await page.locator('[data-audit-search]').fill('Venus de Milo');
  assert.equal(await page.locator('[data-audit-row]:visible').count(), 1);
  await page.goto(`${base}/works/venus-de-milo/#object-record`);
  const fact = page.locator('.v3-facts > div').filter({ has: page.locator('dt', { hasText: /^Dimensions$/ }) });
  assert.match(await fact.innerText(), /H 204 cm/);
  assert.match(await fact.innerText(), /original/);
  assert.match(await fact.locator('a').getAttribute('href'), /cl010277627/);
  assert.equal(await page.locator('[data-spatial]').getAttribute('data-reference-meters'), '2.04');
  await page.locator('#object-record').scrollIntoViewIfNeeded();
  await page.screenshot({ path: '/private/tmp/atrium-dimensions-record.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('#object-record').scrollIntoViewIfNeeded();
  await page.screenshot({ path: '/private/tmp/atrium-dimensions-mobile.png' });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.locator('[data-spatial-open]').click();
  assert.match(await page.locator('[data-spatial-size-note]').innerText(), /original’s documented size/);
  await page.locator('[data-spatial-close]').click();
  await page.goto(`${base}/works/egyptian/portrait-of-nefertiti-smk-cast/#object-record`);
  assert.equal(await page.locator('[data-spatial]').getAttribute('data-reference-meters'), null);
  assert.match(await page.locator('.dimension-note').innerText(), /original bust/);
  await page.goto(`${base}/works/discobolus/#object-record`);
  assert.match(await page.locator('.dimension-note').innerText(), /original have not yet been verified/);
  assert.doesNotMatch(await page.locator('.v3-facts').innerText(), /H 170 cm/);
  assert.deepEqual(errors, []);
  console.log('Dimension browser checks passed: original source notes, no cast fallback, calibrated/uncalibrated AR states, audit filtering and mobile layout.');
} finally { await browser.close(); }
